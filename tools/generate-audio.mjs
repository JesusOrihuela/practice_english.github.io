// ── Slug helper (mirrors slugify in assign-alt-slugs.mjs) ──────────────────
// Capped at SLUG_MAX with an 8-char sha256 suffix when exceeded — keeps audio
// paths within Windows MAX_PATH (260). Must stay identical across the 3 tools.
const SLUG_MAX = 100;
const _slugBase = s =>
  s.toLowerCase()
   .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
   .replace(/[^a-z0-9]+/g, '_')
   .replace(/^_|_$/g, '');
const slugify = s => {
  const base = _slugBase(s);
  if (base.length <= SLUG_MAX) return base;
  const hash = createHash('sha256').update(s, 'utf8').digest('hex').slice(0, 8);
  const head = base.slice(0, SLUG_MAX - 9).replace(/_+$/, '');
  return `${head}_${hash}`;
};

