// ── Helpers for alternative audio ─────────────────────────────────────────

/**
 * Flatten typed, non-style alternatives from the per-pair schema.
 * Reads p.target[i] (i >= 1) where audioSlug is defined.
 * Only entries that already have an audioSlug are included.
 */
function flattenAlts(data) {
  const alts = [];
  for (const p of data.phrases ?? []) {
    const target = p.target ?? [];
    for (let i = 1; i < target.length; i++) {
      const item = target[i];
      if (typeof item === 'object' && item.audioSlug !== undefined)
        alts.push({ audioSlug: item.audioSlug, text: item.text, id: `alt_${item.audioSlug}` });
    }
  }
  return alts;
}

