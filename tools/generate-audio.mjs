// ── Manifest helpers ───────────────────────────────────────────────────────

/**
 * A manifest entry encodes both the stable ID and the synthesized text so
 * that edits to the text of an existing item are also detected as stale.
 * Format: "id\x00text"  (null byte separator — never appears in IDs or text)
 */
function makeSignature(item, src) {
  return `${src.getId(item)}\x00${src.getText(item)}`;
}

function sigId(sig)   { return sig.split('\x00')[0]; }
function sigText(sig) { return sig.split('\x00')[1] ?? ''; }

// ── Load manifest ──────────────────────────────────────────────────────────

let manifest = {};
if (existsSync(MANIFEST_PATH)) {
  try { manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')); }
  catch { console.warn('  [warn] Could not read manifest — skipping stale detection for this run.'); }
}

// ── Stale detection + cleanup (or dry-run report) ─────────────────────────

let totalStaleRemoved  = 0;
let totalStaleReported = 0;

for (const src of sources) {
  if (src.noManifest) continue;   // slug-based sources skip manifest (no position-based stale detection)
  if (!existsSync(src.jsonPath)) continue;

  const data      = JSON.parse(readFileSync(src.jsonPath, 'utf8'));
  const items     = src.getItems(data);
  const currentSigs = items.map(item => makeSignature(item, src));
  const oldSigs     = manifest[src.id] || [];

  // Positions that exist in old manifest with a different signature → stale
  // (catches: position shifts, ID changes, and text edits of existing items)
  const stalePositions = [];
  for (let i = 0; i < oldSigs.length; i++) {
    const currentSig = currentSigs[i];     // undefined if array shrank
    if (currentSig === undefined || currentSig !== oldSigs[i]) {
      stalePositions.push(i);
    }
  }

  if (stalePositions.length === 0) continue;

  if (checkOnly) {
    for (const i of stalePositions) {
      const oldSig = oldSigs[i];
      const cur    = currentSigs[i];
      const oldLabel = `${sigId(oldSig)} "${sigText(oldSig).slice(0, 40)}"`;
      const newLabel = cur ? `${sigId(cur)} "${sigText(cur).slice(0, 40)}"` : '(removed)';
      const oldSlugReport = sigText(oldSigs[i]) ? slugify(sigText(oldSigs[i])) : String(i);
      console.log(`  [stale] ${src.id}/${oldSlugReport}-*.wav`);
      console.log(`          was: ${oldLabel}`);
      console.log(`          now: ${newLabel}`);
      totalStaleReported += (src.voices || VOICES).length;
    }
  } else {
    let srcStale = 0;
    for (const i of stalePositions) {
      const oldSig   = oldSigs[i];
      const oldSlug  = sigText(oldSig) ? slugify(sigText(oldSig)) : String(i);
      for (const voice of (src.voices || VOICES)) {
        const stalePath = resolve(src.outDir, `${oldSlug}-${voice}.wav`);
        if (existsSync(stalePath)) { unlinkSync(stalePath); srcStale++; }
      }
    }
    if (srcStale > 0) {
      console.log(`  [${src.id}] Removed ${srcStale} stale file(s) at ${stalePositions.length} position(s)`);
      totalStaleRemoved += srcStale;
    }
  }
}

// ── Collect missing tasks ──────────────────────────────────────────────────

const tasks = [];
let totalExpected = 0;

for (const src of sources) {
  if (!existsSync(src.jsonPath)) {
    console.warn(`  [skip] JSON not found: ${src.jsonPath}`);
    continue;
  }

  const data  = JSON.parse(readFileSync(src.jsonPath, 'utf8'));
  const items = src.getItems(data);

  mkdirSync(src.outDir, { recursive: true });

  for (let i = 0; i < items.length; i++) {
    for (const voice of (src.voices || VOICES)) {
      totalExpected++;
      const fileIdx = src.getIndex ? src.getIndex(items[i]) : i;
      const outPath = resolve(src.outDir, `${fileIdx}-${voice}.wav`);
      if (!existsSync(outPath)) {
        tasks.push({ src: src.id, i: fileIdx, voice, text: src.getText(items[i]), outPath });
      }
    }
  }
}

// ── Report ─────────────────────────────────────────────────────────────────

const existing = totalExpected - tasks.length;
console.log(`\nAudio check complete`);
const voiceSummary = Object.entries(LANG_VOICES).map(([l, v]) => `${l}:${v.length}`).join(' ');
console.log(`  Expected : ${totalExpected} files (${sources.length} source(s) — voices: ${voiceSummary})`);
console.log(`  Existing : ${existing}`);
console.log(`  Missing  : ${tasks.length}`);
if (totalStaleRemoved  > 0) console.log(`  Stale removed  : ${totalStaleRemoved}`);
if (totalStaleReported > 0) console.log(`  Stale detected : ${totalStaleReported} (dry-run — run without --check to fix)`);

if (tasks.length === 0 && totalStaleReported === 0) {
  console.log('\nAll audio files are up to date.');

  // Always write manifest on a clean run (even if nothing changed) to keep it fresh
  if (!checkOnly) _writeManifest();

  process.exit(0);
}

if (checkOnly) {
  if (tasks.length > 0) {
    console.log('\nMissing files:');
    for (const t of tasks) {
      console.log(`  ${t.src}/${t.i}-${t.voice}.wav  — "${t.text.slice(0, 60)}"`);
    }
  }
  console.log('\n(dry-run — pass without --check to generate)');
  process.exit(0);
}

// ── Generate ───────────────────────────────────────────────────────────────

console.log(`\nLoading Kokoro-82M (dtype=${DTYPE})…`);
const tts = await KokoroTTS.from_pretrained(MODEL, { dtype: DTYPE });
console.log('Model ready.\n');

/** Encode Float32 PCM → 16-bit WAV Buffer */
function encodeWav(samples, sampleRate) {
  const numSamples = samples.length;
  const byteCount  = numSamples * 2;
  const buf        = Buffer.alloc(44 + byteCount);
  buf.write('RIFF', 0); buf.writeUInt32LE(36 + byteCount, 4); buf.write('WAVE', 8);
  buf.write('fmt ', 12); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
  buf.writeUInt32LE(sampleRate, 24); buf.writeUInt32LE(sampleRate * 2, 28);
  buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34);
  buf.write('data', 36); buf.writeUInt32LE(byteCount, 40);
  for (let i = 0; i < numSamples; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    buf.writeInt16LE(Math.round(s * 32767), 44 + i * 2);
  }
  return buf;
}

let generated = 0;
let errors    = 0;

for (const { src, i, voice, text, outPath } of tasks) {
  const label = `[${generated + errors + 1}/${tasks.length}] ${src}/${i}-${voice}.wav`;
  process.stdout.write(`${label} — "${text.slice(0, 50)}"… `);
  try {
    const result = await tts.generate(text, { voice, speed: SPEED });
    writeFileSync(outPath, encodeWav(result.audio, result.sampling_rate));
    console.log('✓');
    generated++;
  } catch (e) {
    console.log(`✗  ${e.message}`);
    errors++;
  }
}

console.log(`\nDone — ${generated} generated, ${errors} errors, ${existing} already existed.`);

// Write manifest after successful generation
if (errors === 0) _writeManifest();

if (errors > 0) process.exit(1);

// ── Manifest writer ────────────────────────────────────────────────────────

function _writeManifest() {
  // Update only the sources that were processed in this run
  for (const src of sources) {
    if (src.noManifest) continue;   // slug-based sources — no position-based stale detection
    if (!existsSync(src.jsonPath)) continue;
    const data  = JSON.parse(readFileSync(src.jsonPath, 'utf8'));
    const items = src.getItems(data);
    manifest[src.id] = items.map(item => makeSignature(item, src));
  }
  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2));
}
