/**
 * generate-audio.mjs — PracticeEnglish Audio Generator
 * ======================================================
 * Checks ALL audio sources and generates any missing WAV files using
 * Kokoro-82M TTS. Existing files are always skipped — safe to re-run
 * at any time, including after adding or editing phrases.
 *
 * STALE AUDIO DETECTION
 * ─────────────────────
 * Audio files are named by slug ({audioSlug}-{voice}.wav). The slug is
 * derived from the phrase or word text and stored in the JSON. Position
 * shifts in the JSON array have no effect on audio files — only text
 * changes cause new files to be generated.
 *
 * When a phrase or word text changes, the slug changes, the old file
 * becomes an orphan (it is simply ignored by the generator), and a new
 * file is generated automatically as a missing file. Run with --prune
 * (future flag) to clean up orphaned files.
 *
 * SOURCES covered:
 *   Phrase topics  → shared/audio/es-en/{topic}/{audioSlug}-{voice}.wav  (EN target)
 *   Vocab general  → shared/audio/vocab/{wordId}-{voice}.wav
 *   Vocab topics   → shared/audio/vocab_{topic}/{wordId}-{voice}.wav
 *
 * USAGE (run from the tools/ directory):
 *   node generate-audio.mjs                  # check + generate everything
 *   node generate-audio.mjs --check          # dry-run: report missing + stale
 *   node generate-audio.mjs --topic greetings          # single phrase topic
 *   node generate-audio.mjs --topic vocab              # general vocab only
 *   node generate-audio.mjs --topic vocab_greetings    # topic vocab only
 *
 * VOICES generated (edit VOICES below to change):
 *   af_heart · af_bella · bf_emma · am_michael
 *
 * REQUIREMENTS:
 *   - Node.js ≥ 18
 *   - kokoro-js installed (npm install in tools/)
 *   - Run from the tools/ directory so relative paths resolve correctly
 */

